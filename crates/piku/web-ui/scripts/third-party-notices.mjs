// Writes the license notices for every npm package bundled into
// crates/piku/src/web/app.js. MIT, ISC and BSD require the copyright and
// permission notice to travel with copies, and most dist files drop it.
//
// Usage: node scripts/third-party-notices.mjs [outfile]
import { build } from "esbuild";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = process.argv[2] ?? path.join(webRoot, "../src/web/THIRD_PARTY_NOTICES.txt");

// Same entry and options as `npm run build`; only the input graph is used.
const result = await build({
  absWorkingDir: webRoot,
  entryPoints: ["app.js"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "safari17",
  loader: { ".css": "css" },
  outfile: "app.js",
  write: false,
  metafile: true,
  logLevel: "error",
});

const packageDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) packageDirs.add(match[1]);
}

const entries = new Map();
for (const dir of packageDirs) {
  const pkg = JSON.parse(readFileSync(path.join(webRoot, dir, "package.json"), "utf8"));
  const id = `${pkg.name}@${pkg.version}`;
  if (entries.has(id)) continue;
  const licenseFile = readdirSync(path.join(webRoot, dir)).find((name) =>
    /^(licen[cs]e|copying|notice)(\.|$)/i.test(name),
  );
  const text = licenseFile
    ? readFileSync(path.join(webRoot, dir, licenseFile), "utf8").trim()
    : `License: ${pkg.license ?? "unknown"} (no license file in the package)` +
      (pkg.author ? `\nAuthor: ${typeof pkg.author === "string" ? pkg.author : pkg.author.name}` : "");
  entries.set(id, text);
}

const ids = [...entries.keys()].sort();
const body = [
  "Third-party software bundled into piku's web UI (crates/piku/src/web/app.js).",
  "Generated by crates/piku/web-ui/scripts/third-party-notices.mjs; do not edit.",
  "",
  ...ids.flatMap((id) => ["=".repeat(72), id, "", entries.get(id), ""]),
].join("\n");

if (!existsSync(path.dirname(outfile))) throw new Error(`missing directory for ${outfile}`);
writeFileSync(outfile, body);
